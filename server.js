import express from 'express';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import { spawn } from 'child_process'; // Import spawn to start the transcoder process
import { error } from 'console';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = 3000;

// establish paths
const FFMPEG_PATH = '/usr/local/bin/ffmpeg';
const hlsOutputDir = path.join(__dirname, 'hls_output');

// keep track of active FFmpeg process in memory
let activeTranscoderProcess = null;

// CORS middleware to allow requests from any origin (specific to video streaming use case)
app.use((req, res, next) => {
    res.header('Access-Control-Allow-Origin', '*');
    res.header('Access-Control-Allow-Headers', 'Origin, X-Requested-With, Content-Type, Accept');
    next();
});


// create a static network route to serve HLS files over HTTP. This allows the client to access the HLS output files generated by FFmpeg.
app.use('/stream', express.static(hlsOutputDir));

// health check route
app.get('/status', (req, res) => {
    res.json({ 
        status: 'online',
        isStreaming: activeTranscoderProcess !== null,
        message: 'Streaming platform API is running'});
});

/**
 * Route to start stream programmatically via HTTP request.
 */
app.get('/start-stream', (req, res) => {
    if (activeTranscoderProcess) {
        return res.status(400).json({error: 'Stream is already running.'});
    }

    // making sure directory is clean and ready
    if (fs.existsSync(hlsOutputDir)) {
        fs.mkdirSync(hlsOutputDir, { recursive: true });
    }

    const inputSource = 'input.mp4';
    const ffmpegArgs = [
        '-re', '-i', inputSource,
        // Split input stream into 3 video channels and scale them to different resolutions
        '-filter_complex', '[0:v]split=3[v1][v2][v3]; [v1]scale=w=1920:h=1080[v1out]; [v2]scale=w=1280:h=720[v2out]; [v3]scale=w=854:h=480[v3out]',

        // encode track 1 (1080p High Quality)
        '-map', '[v1out]', '-c:v:0', 'libx264', '-preset', 'veryfast', '-b:v:0', '5000k', '-maxrate:v:0', '5350k', '-bufsize:v:0', '7500k', '-g:v:0', '60', '-sc_threshold:v:0', '0',

        // encode track 2 (720p Medium Quality)
        '-map', '[v2out]', '-c:v:1', 'libx264', '-preset', 'veryfast', '-b:v:1', '2800k', '-maxrate:v:1', '2996k', '-bufsize:v:1', '4200k', '-g:v:1', '60', '-sc_threshold:v:1', '0',
        
        // encode track 3 (480p Low Quality)
        '-map', '[v3out]', '-c:v:2', 'libx264', '-preset', 'veryfast', '-b:v:2', '1400k', '-maxrate:v:2', '1498k', '-bufsize:v:2', '2100k', '-g:v:2', '60', '-sc_threshold:v:2', '0',

        // map audio to match tracks (higher quality audio goes with higher video bitrate)
        '-map', '0:a', '-c:a:0', 'aac', '-b:a:0', '192k', '-ac', '2',
        '-map', '0:a', '-c:a:1', 'aac', '-b:a:1', '128k', '-ac', '2',
        '-map', '0:a', '-c:a:2', 'aac', '-b:a:2', '96k', '-ac', '2',

        // HLS segmenting options
        '-f', 'hls',
        '-hls_time', '4',              // split stream into uniform 4 second freagments
        '-hls_playlist_type', 'event',  // Persistent mode: keeps all fragments for VOD playback
        '-hls_segment_filename', path.join(hlsOutputDir, 'segment_%v_%03d.ts'), // segment file name pattern
        '-master_pl_name', 'master.m3u8', // master file index that lists the streams for the Ui player
        '-var_stream_map', 'v:0,a:0 v:1, a:1 v:2,a:2', // pairs video and audio tracks together
        path.join(hlsOutputDir, 'stream_%v.m3u8') // output file pattern for each stream
        ];

        console.log('web API spawning automated FFmpeg instance...')
        activeTranscoderProcess = spawn(FFMPEG_PATH, ffmpegArgs);

        // capture logs to server console for debugging
        activeTranscoderProcess.stderr.on('data', (data) => {
            console.log(`[FFmpeg-Engine]: ${data.toString().trim()}`);
        });

        activeTranscoderProcess.on('close', (code) => {
            console.log(`FFmpeg engline closed. Exit code ${code}`);
            activeTranscoderProcess = null; // reset the process reference
            finalizeVOD(); // call the function to finalize VOD after transcoding is done
        });

        res.json({ message: 'Stream started successfully.', playlistUrl: `http://localhost:${PORT}/stream/master.m3u8` });
})

// Route to stop the stream programmatically via HTTP request.
app.get('/stop-stream', (req, res) => {
    if (!activeTranscoderProcess) {
        return res.status(400).json({ error: 'No stream is running' });
    }
    console.log('kill signal received. Stopping FFmpeg transcoder process...');
    activeTranscoderProcess.kill('SIGINT'); // send a graceful termination signal to FFmpeg
    res.json({ message: 'Stream stopped successfully.' });
})

// function to go from live streaming to VOD mode when streaming is completed.
function finalizeVOD() {
    console.log('streaming completed. Finalizing VOD playlist...');

    // define the 3 separate playlists created by FFmpeg ABR transcoding
    const playlistfiles = ['stream_0.m3u8', 'stream_1.m3u8', 'stream_2.m3u8'];
    const endTag = '\n#EXT-X-ENDLIST\n';
    // append the end tag to each of the 3 playlists to mark them as complete

    playlistfiles.forEach((file) => {
        const filePath = path.join(hlsOutputDir, file);

        // check if the playlist file exists before editing
        if (fs.existsSync(filePath)) {
            try {
                // read the current text of the playlist file
                const content = fs.readFileSync(filePath, 'utf8');
                // if the file doesnr already have the end list tag,  append it.
                if (!content.includes('#EXT-X-ENDLIST')) {
                    fs.appendFileSync(filePath, endTag, 'utf8');
                    console.log(`locked VOD file structure for variant: ${file}`);
                }
            } catch (error) {
                console.error(`Error finalizing VOD playlist ${file}:`, error);
            }
        } else {
            console.log(`warning: could not find playlist ${file} to finalize`);
        }
    })
    console.log('VOD playlist finalization complete. All playlists are now ready for playback.');
}

app.listen(PORT, () => {
    console.log(`control server is running on http://localhost:${PORT}`);
    console.log(`Public Master Playlist Route: http://localhost:${PORT}/stream/master.m3u8`);
})